const gallery=document.getElementById('gallery'),dialog=document.getElementById('lightbox');let visible=photos.slice(),current=0;
function render(){gallery.replaceChildren();visible.forEach(p=>{const figure=document.createElement('figure');figure.className='photo';const button=document.createElement('button');button.className='image-button';button.setAttribute('aria-label','View '+p.title);const img=document.createElement('img');img.src=p.file+'.jpg';img.alt=p.alt;img.loading='lazy';img.width=p.w;img.height=p.h;button.append(img);const arrow=document.createElement('span');arrow.className='view';arrow.textContent='↗';arrow.setAttribute('aria-hidden','true');button.append(arrow);button.addEventListener('click',()=>{current=visible.indexOf(p);updateViewer();dialog.showModal()});const caption=document.createElement('figcaption');caption.className='caption';const title=document.createElement('span');title.textContent=p.title;const category=document.createElement('span');category.textContent=p.category;caption.append(title,category);figure.append(button,caption);gallery.append(figure)});document.getElementById('count').textContent='Showing '+visible.length+(visible.length===1?' photograph':' photographs')}
function updateViewer(){const p=visible[current];document.getElementById('large').src=p.file+'.jpg';document.getElementById('large').alt=p.alt;document.getElementById('photo-title').textContent=p.title;document.getElementById('viewer-count').textContent=String(current+1).padStart(2,'0')+' / '+String(visible.length).padStart(2,'0')}
document.querySelectorAll('[data-filter]').forEach(b=>b.addEventListener('click',()=>{document.querySelectorAll('[data-filter]').forEach(x=>{x.classList.toggle('active',x===b);x.setAttribute('aria-pressed',String(x===b))});visible=photos.filter(p=>b.dataset.filter==='All'||p.category===b.dataset.filter);render()}));
document.getElementById('close').onclick=()=>dialog.close();function step(n){current=(current+n+visible.length)%visible.length;updateViewer()}document.getElementById('previous').onclick=()=>step(-1);document.getElementById('next').onclick=()=>step(1);dialog.addEventListener('keydown',e=>{if(e.key==='ArrowRight')step(1);if(e.key==='ArrowLeft')step(-1)});dialog.addEventListener('click',e=>{if(e.target===dialog){const r=dialog.getBoundingClientRect();if(e.clientX<r.left||e.clientX>r.right||e.clientY<r.top||e.clientY>r.bottom)dialog.close()}});render();
